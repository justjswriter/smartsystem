type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, params?: Record<string, string | number | null | undefined>) => string;
  label: (prefix: string, value: string | null | undefined) => string;
  formatDate: (value: string | Date | null | undefined) => string;
  formatDateTime: (value: string | Date | null | undefined) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function getInitialLanguage(): Language {
  const stored = localStorage.getItem(LANGUAGE_KEY);
  return stored === "kk" || stored === "ru" || stored === "en" ? stored : "kk";
}

function localeFor(language: Language) {
  return language === "kk" ? "kk-KZ" : language === "ru" ? "ru-RU" : "en-US";
}

const kkMonths = [
  "қаңтар",
  "ақпан",
  "наурыз",
  "сәуір",
  "мамыр",
  "маусым",
  "шілде",
  "тамыз",
  "қыркүйек",
  "қазан",
  "қараша",
  "желтоқсан",
];

function padTimePart(value: number) {
  return String(value).padStart(2, "0");
}

function formatKazakhDate(date: Date, includeTime: boolean) {
  const base = `${date.getDate()} ${kkMonths[date.getMonth()]} ${date.getFullYear()} ж.`;
  if (!includeTime) {
    return base;
  }
  return `${base}, ${padTimePart(date.getHours())}:${padTimePart(date.getMinutes())}`;
}

function humanizeEnum(value: string | null | undefined) {
  if (!value) {
    return "--";
  }
  return value
    .replace(/_/g, " ")
    .split(" ")
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(getInitialLanguage);

  const value = useMemo<I18nContextValue>(() => {
    const locale = localeFor(language);
    const dictionary = dictionaries[language];

    function translate(key: string, params?: Record<string, string | number | null | undefined>) {
      const value = dictionary[key] ?? dictionaries.kk[key] ?? key;
      return typeof value === "function" ? value(params) : value;
    }

    function enumLabel(prefix: string, rawValue: string | null | undefined) {
      if (!rawValue) {
        return "--";
      }
      const key = `${prefix}.${rawValue}`;
      const translated = translate(key);
      return translated === key ? humanizeEnum(rawValue) : translated;
    }

    function format(value: string | Date | null | undefined, options: Intl.DateTimeFormatOptions, includeTime = false) {
      if (!value) {
        return translate("common.notSet");
      }
      const date = value instanceof Date ? value : new Date(value);
      if (Number.isNaN(date.getTime())) {
        return translate("common.notSet");
      }
      if (language === "kk") {
        return formatKazakhDate(date, includeTime);
      }
      return new Intl.DateTimeFormat(locale, options).format(date);
    }

    return {
      language,
      setLanguage(nextLanguage) {
        localStorage.setItem(LANGUAGE_KEY, nextLanguage);
        setLanguageState(nextLanguage);
      },
      t: translate,
      label: enumLabel,
      formatDate(value) {
        return format(value, { year: "numeric", month: "long", day: "numeric" });
      },
      formatDateTime(value) {
        return format(value, {
          year: "numeric",
          month: "long",
          day: "numeric",
          hour: "2-digit",
          minute: "2-digit",
        }, true);
      },
    };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used within LanguageProvider");
  }
  return context;
}
